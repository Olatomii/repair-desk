import { signIn } from "./auth-helper";
import { test, expect, type APIRequestContext } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { hashPassword } from "better-auth/crypto";
import { prisma } from "../src/lib/prisma";

test("operator administration, applications, cancellation and dispute resolution", async ({ browser, baseURL }) => {
  test.setTimeout(120_000);
  if (!baseURL || !["localhost", "127.0.0.1"].includes(new URL(baseURL).hostname) || !["localhost", "127.0.0.1"].includes(new URL(process.env.DATABASE_URL!).hostname)) throw Error("Local fixtures only");
  const password = "Operations-test-password-2026!";
  const account = async (role: "CLIENT" | "OPERATOR") => {
    const id = randomUUID();
    const user = await prisma.user.create({ data: { id, email: `${id}@example.invalid`, name: `Operations ${id}`, role, accounts: { create: { id: randomUUID(), accountId: id, providerId: "credential", password: await hashPassword(password) } } } });
    const context = await browser.newContext({ baseURL });
    const result = await signIn(context.request, baseURL, user.email, password);
    expect(result.ok(), await result.text()).toBeTruthy();
    return { user, context, api: context.request };
  };
  const operator = await account("OPERATOR"), client = await account("CLIENT"), applicant = await account("CLIENT"), stranger = await account("CLIENT");
  const post = (api: APIRequestContext, data: object) => api.post("/api/operator", { data });
  const city = await prisma.city.findFirstOrThrow({ where: { isActive: true } });
  const service = await prisma.serviceCategory.findFirstOrThrow({ where: { isActive: true } });
  try {
    expect((await post(client.api, { action: "SET_OPERATOR", email: client.user.email, operator: true })).status()).toBe(403);
    expect((await post(operator.api, { action: "SET_OPERATOR", email: operator.user.email, operator: false })).status()).toBe(409);
    expect((await operator.api.post("/api/operator", { data: {}, headers: { origin: "https://evil.invalid" } })).status()).toBe(403);
    const applicationPage = await applicant.context.newPage();
    await applicationPage.goto("/apply");
    await applicationPage.getByLabel("Phone number").fill("+234 800 123 4567");
    await applicationPage.getByLabel("Experience and qualifications").fill("Five years of practical repair experience and training.");
    await applicationPage.getByLabel(city.name, { exact: true }).check();
    await applicationPage.getByLabel(service.name, { exact: true }).check();
    await applicationPage.getByRole("button", { name: "Submit application" }).click();
    await expect(applicationPage.getByText("Application status: PENDING")).toBeVisible();
    let profile = await prisma.artisanProfile.findUniqueOrThrow({ where: { userId: applicant.user.id } });
    expect((await prisma.user.findUniqueOrThrow({ where: { id: applicant.user.id } })).role).toBe("CLIENT");
    const review = (status: "ACTIVE" | "SUSPENDED", snapshot = profile.updatedAt.toISOString()) => post(operator.api, { action: "REVIEW_ARTISAN", id: profile.id, expectedUpdatedAt: snapshot, status, cityIds: [city.id], serviceIds: [service.id] });
    const stale = profile.updatedAt.toISOString();
    const manage = await operator.context.newPage();
    await manage.goto("/operator/manage");
    await manage.getByText(`${applicant.user.name} — PENDING`, { exact: true }).click();
    const application = manage.locator("details").filter({ has: manage.getByText(`${applicant.user.name} — PENDING`, { exact: true }) });
    await application.getByLabel("Account decision").selectOption("ACTIVE");
    await application.getByRole("button", { name: "Save changes" }).click();
    await expect(manage.getByText(`${applicant.user.name} — ACTIVE`, { exact: true })).toBeVisible();
    expect((await review("SUSPENDED", stale)).status()).toBe(409);
    profile = await prisma.artisanProfile.findUniqueOrThrow({ where: { id: profile.id } });
    expect((await prisma.user.findUniqueOrThrow({ where: { id: applicant.user.id } })).role).toBe("ARTISAN");
    expect((await applicant.api.post("/api/artisan-application", { data: { phone: "+2348001234567", bio: "Try to replace operator approved coverage", cityIds: [city.id], serviceIds: [service.id] } })).status()).toBe(403);
    const makeBooking = () => prisma.booking.create({ data: { clientId: client.user.id, reference: `OPS-${randomUUID()}`, cityId: city.id, serviceCategoryId: service.id, problemDescription: "Operations regression repair", address: "Local test only" } });
    let booking = await makeBooking();
    const action = (api: APIRequestContext, name: string, extra: object = {}, snapshot = booking.updatedAt.toISOString()) => api.post(`/api/bookings/${booking.id}/action`, { data: { action: name, expectedUpdatedAt: snapshot, ...extra } });
    const refresh = async () => { booking = await prisma.booking.findUniqueOrThrow({ where: { id: booking.id } }); };
    expect((await action(stranger.api, "CANCEL_BOOKING", { reason: "Not my booking cancellation" })).status()).toBe(403);
    const clientPage = await client.context.newPage();
    await clientPage.goto("/client");
    const repair = clientPage.locator("article").filter({ hasText: booking.reference });
    await repair.locator("summary").filter({ hasText: "Cancel repair" }).click();
    await repair.getByLabel("Reason").fill("Client no longer needs this repair.");
    await repair.getByRole("button", { name: "Cancel repair", exact: true }).click();
    await expect(repair.getByText("CANCELLED", { exact: true })).toBeVisible();
    await refresh();
    expect((await action(operator.api, "ASSIGN_ARTISAN", { artisanId: profile.id })).status()).toBe(409);
    booking = await makeBooking();
    expect((await review("SUSPENDED")).status()).toBe(200);
    expect((await action(operator.api, "ASSIGN_ARTISAN", { artisanId: profile.id })).status()).toBe(409);
    profile = await prisma.artisanProfile.findUniqueOrThrow({ where: { id: profile.id } });
    expect((await review("ACTIVE")).status()).toBe(200);
    expect((await action(operator.api, "ASSIGN_ARTISAN", { artisanId: profile.id })).status()).toBe(200); await refresh();
    expect((await action(applicant.api, "SUBMIT_QUOTE", { amount: 1000 })).status()).toBe(200); await refresh();
    expect((await action(client.api, "APPROVE_QUOTE")).status()).toBe(200); await refresh();
    expect((await action(applicant.api, "START_WORK")).status()).toBe(200); await refresh();
    expect((await action(client.api, "CANCEL_BOOKING", { reason: "Cannot cancel after starting" })).status()).toBe(409);
    expect((await action(stranger.api, "OPEN_DISPUTE", { reason: "Unauthorized dispute attempt" })).status()).toBe(403);
    const disputeVersion = booking.updatedAt.toISOString();
    const opened = await Promise.all([client.api, applicant.api].map(api => action(api, "OPEN_DISPUTE", { reason: "Repair needs an operator review" }, disputeVersion)));
    expect(opened.map(r => r.status()).sort()).toEqual([200, 409]); await refresh();
    expect((await action(applicant.api, "MARK_WORK_COMPLETE")).status()).toBe(409);
    expect((await action(client.api, "RESOLVE_DISPUTE", { reason: "Trying to resolve my own dispute", resolution: "RESUME" })).status()).toBe(403);
    const disputeSnapshot = booking.updatedAt.toISOString();
    expect((await action(operator.api, "RESOLVE_DISPUTE", { reason: "Both parties agreed to resume the repair", resolution: "RESUME" })).status()).toBe(200); await refresh();
    expect(booking.status).toBe("IN_PROGRESS");
    expect((await action(operator.api, "RESOLVE_DISPUTE", { reason: "Stale duplicate resolution", resolution: "CANCEL" }, disputeSnapshot)).status()).toBe(409);
    expect((await action(applicant.api, "MARK_WORK_COMPLETE")).status()).toBe(200); await refresh();
    expect((await action(client.api, "CONFIRM_HANDOVER")).status()).toBe(200); await refresh();
    const jobsDone = (await prisma.artisanProfile.findUniqueOrThrow({ where: { id: profile.id } })).jobsDone;
    expect((await action(client.api, "OPEN_DISPUTE", { reason: "A problem appeared after collection" })).status()).toBe(200); await refresh();
    expect((await action(operator.api, "RESOLVE_DISPUTE", { reason: "Completed repair cannot be cancelled", resolution: "CANCEL" })).status()).toBe(409);
    expect((await action(operator.api, "RESOLVE_DISPUTE", { reason: "Follow-up resolved the reported issue", resolution: "RESUME" })).status()).toBe(200); await refresh();
    expect(booking.status).toBe("COMPLETED");
    expect((await prisma.artisanProfile.findUniqueOrThrow({ where: { id: profile.id } })).jobsDone).toBe(jobsDone);
    booking = await prisma.booking.create({ data: { clientId: client.user.id, artisanId: profile.id, status: "QUOTE_APPROVED", reference: `OPS-${randomUUID()}`, cityId: city.id, serviceCategoryId: service.id, problemDescription: "Cancellation by operator after dispute" } });
    expect((await action(client.api, "OPEN_DISPUTE", { reason: "Parties cannot agree on the repair" })).status()).toBe(200); await refresh();
    expect((await action(operator.api, "RESOLVE_DISPUTE", { reason: "Both parties agreed to cancel this repair", resolution: "CANCEL" })).status()).toBe(200); await refresh();
    expect(booking.status).toBe("CANCELLED");
    expect(await prisma.notification.count({ where: { userId: operator.user.id, title: "Repair dispute opened" } })).toBeGreaterThan(0);
    const slug = `test-${randomUUID()}`;
    const added = await post(operator.api, { action: "CREATE_CITY", slug, name: "Regression City", state: "Test State", country: "Nigeria" });
    expect(added.status()).toBe(200);
    const addedCity = await prisma.city.findUniqueOrThrow({ where: { id: (await added.json()).id } });
    const updateCity = { action: "UPDATE_CITY", id: addedCity.id, expectedUpdatedAt: addedCity.updatedAt.toISOString(), name: addedCity.name, state: addedCity.state, country: addedCity.country, isActive: false };
    expect((await post(operator.api, updateCity)).status()).toBe(200);
    expect((await post(operator.api, updateCity)).status()).toBe(409);
    const addedService = await post(operator.api, { action: "CREATE_SERVICE", slug, name: "Regression Service", description: "Local test service coverage", mode: "WORKSHOP" });
    expect(addedService.status()).toBe(200);
    const serviceRecord = await prisma.serviceCategory.findUniqueOrThrow({ where: { id: (await addedService.json()).id } });
    expect((await post(operator.api, { action: "UPDATE_SERVICE", id: serviceRecord.id, expectedUpdatedAt: serviceRecord.updatedAt.toISOString(), name: serviceRecord.name, description: serviceRecord.description, isActive: false })).status()).toBe(200);
    expect((await post(operator.api, { action: "SET_OPERATOR", email: stranger.user.email, operator: true })).status()).toBe(200);
    expect((await post(stranger.api, { action: "SET_OPERATOR", email: client.user.email, operator: true })).status()).toBe(401); // old sessions revoked
    expect((await post(operator.api, { action: "SET_OPERATOR", email: stranger.user.email, operator: false })).status()).toBe(200);
    for (const width of [320, 768, 1024, 1440]) {
      await manage.setViewportSize({ width, height: 900 });
      expect(await manage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    }
    await prisma.city.delete({ where: { id: addedCity.id } });
    await prisma.serviceCategory.delete({ where: { id: serviceRecord.id } });
  } finally {
    await Promise.all([operator, client, applicant, stranger].map(a => a.context.close()));
    await prisma.booking.deleteMany({ where: { clientId: client.user.id } });
    await prisma.user.deleteMany({ where: { id: { in: [operator, client, applicant, stranger].map(a => a.user.id) } } });
  }
});
